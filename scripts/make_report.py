"""Build docs/RESULTS.md from the JSON files written by training / evaluation / benchmarking. Never hand-edited."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "experiments" / "results"
METRICS = [("sm", "S↑"), ("wf", "Fβw↑"), ("em", "E↑"), ("mae", "MAE↓"), ("miou", "mIoU↑"), ("dice", "Dice↑")]
ORDER = ["rgb", "reliability", "concat", "cross_attn", "gated"]
NAMES = {"rgb": "RGB-only", "concat": "Concat + proj", "cross_attn": "Cross-attention", "gated": "Gated cross-attn",
         "reliability": "Reliability-aware"}


def load(p):
    return json.loads(p.read_text()) if p.exists() else None


def row(label, res):
    if not res:
        return f"| {label} | " + " | ".join("n/a" for _ in METRICS) + " | n/a |"
    return f"| {label} | " + " | ".join(f"{res[k]:.4f}" for k, _ in METRICS) + f" | {res['n']} |"


def table(title, rows):
    head = "| Model | " + " | ".join(h for _, h in METRICS) + " | N |\n|---|" + "---|" * (len(METRICS) + 1)
    return f"### {title}\n\n{head}\n" + "\n".join(rows) + "\n"


def main():
    out = ["# Measured results", "", "Generated by `scripts/make_report.py` from `experiments/results/*.json`. "
           "Rows marked n/a were not run. Single seed, short training budget — see README for caveats.", ""]
    exps = {v: next(iter(sorted((ROOT / "experiments").glob(f"abl_{v}_e*/summary.json"))), None) for v in ORDER}
    t = [f"| {NAMES[v]} | {load(p)['epochs_run']} | {load(p)['params_total']/1e6:.2f} | {load(p)['train_seconds']/60:.0f} |"
         for v, p in exps.items() if p]
    if t:
        out += ["### Training runs", "", "| Model | Epochs | Params (M) | Train min |", "|---|---|---|---|", *t, ""]
    main_rows = []
    for v in ORDER:
        d = load(R / f"{v}_test.json")
        main_rows.append(row(NAMES[v] + (" (depth)" if v != "rgb" else ""), d and d["results"]["cod10k"]))
    out.append(table("COD10K test: each model in its intended mode", main_rows))
    nd = [row(NAMES[v] + " (depth withheld)", (d := load(R / f"{v}_test_nodepth.json")) and d["results"]["cod10k"]) for v in ORDER[1:]]
    out.append(table("COD10K test: fusion models with depth withheld (RGB path)", nd))
    for mode in ("shuffle", "noise", "constant"):
        rs = [row(NAMES[v], (d := load(R / f"{v}_test_degrade_{mode}.json")) and d["results"]["cod10k"]) for v in ORDER[1:]]
        out.append(table(f"COD10K test: depth degraded ({mode}, severity 1.0)", rs))
    bench = ["| Model | Params (M) | Ckpt (MB) | RGB-only ms | MM cached-depth ms | MM incl. depth ms | Device |", "|---|---|---|---|---|---|---|"]
    for v in ORDER:
        b = load(R / f"{v}_bench.json")
        if b:
            g = lambda k: f"{b[k]['mean_ms']:.0f}" if k in b else "–"
            bench.append(f"| {NAMES[v]} | {b['params_m']:.1f} | {b['checkpoint_mb']:.0f} | {g('rgb_only')} | {g('multimodal_depth_cached')} | {g('multimodal_depth_uncached')} | {b['device']} |")
    out += ["### Efficiency (single image, batch 1)", "", *bench, ""]
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out))
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    sys.exit(main())
